"""Writes src/platform/default_font_data.{hpp,cpp}: the engine's built-in 8x8 font.

The glyphs are the public domain 8x8 VGA font (Marcel Sondaar / IBM public
domain VGA fonts, "License: Public Domain") that SDL3 ships as its debug-text
font in src/render/SDL_render_debug_font.h; this reads them from the SDL
sources CMake fetched. Codes 33..126 and 161..255; space and U+00A0 are blank.

usage: python tools/make_default_font.py [path/to/SDL_render_debug_font.h]
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT = ROOT / "build" / "dev" / "_deps" / "sdl3-src" / "src" / "render" / "SDL_render_debug_font.h"
CODES = list(range(33, 127)) + list(range(161, 256))

HEADER = """#pragma once

#include <array>
#include <cstdint>

// Generated by tools/make_default_font.py; do not edit.
// The built-in 8x8 font: public domain VGA glyphs (Marcel Sondaar / IBM),
// as shipped by SDL3 for its debug text. Row bytes, bit 0 = leftmost pixel.
namespace alpha::platform {

// Glyphs for U+0021..U+007E then U+00A1..U+00FF, 8 bytes each (top row first).
inline constexpr int kDefaultFontCells = {cells};
extern const std::array<std::uint8_t, {size}> kDefaultFontBits;
// Where the glyphs come from and their license, for THIRD_PARTY_NOTICES.
extern const char* const kDefaultFontLicense;

}}  // namespace alpha::platform
"""

LICENSE = ("alpha-star built-in font: 8x8 VGA glyphs from font8_8.asm by Marcel Sondaar, "
           "derived from the International Business Machines public domain VGA fonts. "
           "License: Public Domain.")


def main():
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    text = src.read_text(encoding="utf-8", errors="replace")
    body = text[text.index("SDL_RenderDebugTextFontData[]"):]
    values = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2}),", body)]
    data = values[: len(CODES) * 8]
    assert len(data) == len(CODES) * 8, len(data)
    assert "License:" in text and "Public Domain" in text, "license line not found"
    out = ROOT / "src" / "platform"
    (out / "default_font_data.hpp").write_text(
        HEADER.replace("{cells}", str(len(CODES))).replace("{size}", str(len(data))).replace("}}", "}"),
        encoding="utf-8", newline="\n")
    rows = []
    for i in range(0, len(data), 32):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 32]) + ",")
    cpp = ("#include \"platform/default_font_data.hpp\"\n\n"
           "// Generated by tools/make_default_font.py; do not edit.\n"
           "namespace alpha::platform {\n\n"
           f"const std::array<std::uint8_t, {len(data)}> kDefaultFontBits{{{{\n" + "\n".join(rows) + "\n}};\n\n"
           f"const char* const kDefaultFontLicense =\n    \"{LICENSE}\";\n\n"
           "}  // namespace alpha::platform\n")
    (out / "default_font_data.cpp").write_text(cpp, encoding="utf-8", newline="\n")
    print(f"wrote {len(CODES)} glyphs")


if __name__ == "__main__":
    main()
